create table if not exists dialog
(
    id                  bigint          primary key generated by default as identity,
    product_id      	bigint          not null references product(id),
    buyer_id            bigint          not null references "user"(id),
    created_at		    timestamptz     not null,
    updated_at          timestamptz     not null
);

comment on table dialog is 'Таблица, содержащая информацию о диалогах между покупателем и продавцом';

comment on column dialog.id is 'Уникальный идентификатор диалога';
comment on column dialog.product_id is 'Внешний ключ на товар';
comment on column dialog.buyer_id is 'Внешний ключ на покупателя (пользователя)';
comment on column dialog.created_at is 'Дата создания диалога';
comment on column dialog.updated_at is 'Дата последнего обновления диалога';